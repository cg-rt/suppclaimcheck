"""Builds the generated views of the architecture map (P0.4).

From docs/architecture/architecture.yaml it writes:
- docs/architecture/viewer/map-data.js: the map as JSON for the offline viewer. A script file
  rather than a .json file, because browsers refuse to fetch local files opened from disk.
- the Mermaid diagram in README.md, between the map:start and map:end markers.

Run: uv run python tools/map_build.py           (rewrite the generated files)
     uv run python tools/map_build.py --check   (exit 1 if any is out of date; used in CI)
"""

import json
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
MAP_PATH = Path("docs/architecture/architecture.yaml")
DATA_PATH = Path("docs/architecture/viewer/map-data.js")
README_PATH = Path("README.md")

MARKERS = re.compile(r"<!-- map:start.*?-->.*?<!-- map:end -->", re.DOTALL)
START = (
    "<!-- map:start: generated by tools/map_build.py from "
    "docs/architecture/architecture.yaml. Edit the YAML, not this block. -->"
)
END = "<!-- map:end -->"


def node_id(module_id: str) -> str:
    return "m_" + re.sub(r"\W", "_", module_id)


def label(text: str) -> str:
    """Quotes a Mermaid label; double quotes inside it become #quot;."""
    return '"' + text.replace('"', "#quot;") + '"'


def module_label(module: dict) -> str:
    text = module["id"] + (f": {module['role']}" if module.get("role") else "")
    if module.get("containers", [module["id"]]) != [module["id"]]:
        text += "<br/>" + " + ".join(module["containers"])
    return text


def mermaid(map_data: dict) -> str:
    """The README diagram: modules inside the host, the entry path in, and outside services."""
    system = map_data.get("system", {})
    modules = map_data.get("modules", [])
    by_name = {}
    for module in modules:
        by_name[module["id"]] = module["id"]
        for container in module.get("containers", []):
            by_name[container] = module["id"]
    internet = {n["id"] for n in map_data.get("networks", []) if n.get("internet")}
    entry = system.get("entry")

    lines = ["flowchart LR"]
    if entry:
        lines.append(
            f"  client([{label(entry['client'])}]) --> entry[{label(entry['via'])}]"
        )
    lines.append(f"  subgraph host [{label(system.get('host_label', 'Host'))}]")
    for module in modules:
        text = label(module_label(module))
        shape = f"[({text})]" if module.get("kind") == "datastore" else f"[{text}]"
        lines.append(f"    {node_id(module['id'])}{shape}")
    lines.append("  end")
    if entry:
        lines.append(f"  entry --> {node_id(entry['module'])}")

    for module in modules:
        seen = []
        for dep in module.get("depends_on", []):
            if dep not in by_name:
                raise ValueError(f"module {module['id']}: unknown dependency {dep!r}")
            target = by_name[dep]
            if target != module["id"] and target not in seen:
                seen.append(target)
                lines.append(f"  {node_id(module['id'])} --> {node_id(target)}")
    for module in modules:
        apis = module.get("external_apis") or []
        if apis and not (entry and module["id"] == entry["module"]):
            ext = "x_" + node_id(module["id"])[2:]
            lines.append(
                f"  {node_id(module['id'])} --> {ext}([{label(', '.join(apis))}])"
            )

    egress = [m for m in modules if internet & set(m.get("networks", []))]
    if egress:
        lines.append("  classDef egress stroke-dasharray: 5 4")
        lines.append(
            "  class " + ",".join(node_id(m["id"]) for m in egress) + " egress"
        )
    return "\n".join(lines)


def readme_block(map_data: dict) -> str:
    modules = map_data.get("modules", [])
    internet = {n["id"] for n in map_data.get("networks", []) if n.get("internet")}
    egress = [f"`{m['id']}`" for m in modules if internet & set(m.get("networks", []))]
    note = ""
    if egress:
        names = " and ".join(egress) if len(egress) <= 2 else ", ".join(egress)
        note = (
            f"\n\nOnly {names} can reach the internet (dashed outline). "
            "Everything else runs on an internal network."
        )
    return f"{START}\n```mermaid\n{mermaid(map_data)}\n```{note}\n{END}"


def data_js(map_data: dict) -> str:
    body = json.dumps(map_data, indent=2, ensure_ascii=False, default=str)
    return (
        f"// Generated by tools/map_build.py from {MAP_PATH.as_posix()}. Do not edit.\n"
        f"window.ARCHITECTURE_MAP = {body};\n"
    )


def with_block(readme: str, block: str) -> str:
    if not MARKERS.search(readme):
        raise ValueError("README.md has no map:start / map:end markers")
    return MARKERS.sub(lambda _: block, readme, count=1)


def expected_files(root: Path) -> dict[Path, str]:
    map_data = yaml.safe_load((root / MAP_PATH).read_text(encoding="utf-8"))
    readme = (root / README_PATH).read_text(encoding="utf-8")
    return {
        DATA_PATH: data_js(map_data),
        README_PATH: with_block(readme, readme_block(map_data)),
    }


def stale_files(root: Path) -> list[Path]:
    stale = []
    for path, content in expected_files(root).items():
        target = root / path
        if not target.exists() or target.read_text(encoding="utf-8") != content:
            stale.append(path)
    return stale


def main(argv: list[str]) -> int:
    if "--check" in argv:
        stale = stale_files(ROOT)
        for path in stale:
            print(f"map_build: {path.as_posix()} is out of date")
        if stale:
            print(
                "map_build: run `uv run python tools/map_build.py` and commit the result."
            )
            return 1
        print("map_build: generated files are up to date.")
        return 0
    for path, content in expected_files(ROOT).items():
        target = ROOT / path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content, encoding="utf-8", newline="\n")
        print(f"map_build: wrote {path.as_posix()}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
